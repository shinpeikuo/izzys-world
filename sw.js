self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    const older = [];
    for (const key of await caches.keys()) {
      if (key.startsWith('izzys-world-') && key !== CACHE) older.push(await caches.open(key));
    }
    const copyOrDownload = async (file) => {
      for (const old of older) {
        const hit = await old.match(file); // same name and same fingerprint: unchanged
        if (hit) return cache.put(file, hit);
      }
      const response = await fetch(new Request(file, { cache: 'reload' }));
      if (!response.ok) throw new Error('Could not download ' + file);
      return cache.put(file, response);
    };
    // A few at a time, so a slow connection isn't swamped.
    const queue = [...FILES];
    const worker = async () => { while (queue.length) await copyOrDownload(queue.shift()); };
    await Promise.all(Array.from({ length: 6 }, worker));
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('izzys-world-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('message', (event) => {
  if (event.data === 'SKIP_WAITING') self.skipWaiting();
});

// Cache first: the game always loads from the tablet, never waits on the network.
self.addEventListener('fetch', (event) => {
  if (event.request.method !== 'GET') return;
  if (self.location.hostname === 'localhost') return; // testing on the computer: always use the latest files
  event.respondWith(
    caches.match(event.request, { ignoreSearch: true }).then((hit) => hit || fetch(event.request))
  );
});
